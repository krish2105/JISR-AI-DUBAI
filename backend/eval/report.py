"""
report.py — Write docs/EVAL_REPORT.md from the latest result files (never by hand).

The report shows every number with its suite, dataset version, git commit and model profile,
the gate table, per-slice breakdowns (language, difficulty, split), and the worst failures of
each suite (error analysis). Bad numbers are reported as they are.
"""

import json

import yaml

from eval.common import REPO, latest_results
from eval.gate import BASELINE, THRESHOLDS, evaluate, markdown

REPORT = REPO / "docs" / "EVAL_REPORT.md"

INTRO = """# Evaluation report

Generated by `make eval` from `backend/eval/results/` — do not edit by hand.
Datasets: `data/synthetic/` (see its README for how they were built). Methods: docstrings in `backend/eval/suites/`.
Statuses: PASS · FAIL (hard gate) · TARGET (not yet met; becomes a hard gate in the phase shown) · REGRESSED.
"""


def build() -> str:
    """Assemble the markdown report."""
    results = latest_results()
    if not results:
        return INTRO + "\nNo results yet. Run `make eval`.\n"
    thresholds = yaml.safe_load(THRESHOLDS.read_text())
    baseline = json.loads(BASELINE.read_text()) if BASELINE.exists() else {}
    rows, failed = evaluate(results, thresholds, baseline)
    any_res = next(iter(results.values()))
    out = [INTRO,
           f"**Run:** commit `{any_res['git_sha']}` · profile `{any_res['llm_profile']}` "
           f"({', '.join(f'{k}={v}' for k, v in any_res['models'].items() if k != 'stt')}) · "
           f"dataset `{any_res['dataset_version']}` · split `{any_res['split']}` · {any_res['timestamp']}",
           f"\n**Gate: {'FAILED' if failed else 'PASSED'}**\n", markdown(rows), ""]
    for suite, res in sorted(results.items()):
        out.append(f"\n## {suite}  (n = {res['n']})\n")
        out.append("| metric | value |\n|---|---|")
        out += [f"| {k} | {v:.3f} |" for k, v in res["metrics"].items()]
        if res["slices"]:
            out.append("\n| slice | " + " | ".join(next(iter(res["slices"].values())).keys()) + " |")
            out.append("|---|" + "---|" * len(next(iter(res["slices"].values()))))
            out += [f"| {name} | " + " | ".join(f"{v:.3f}" for v in vals.values()) + " |"
                    for name, vals in res["slices"].items()]
        if res["failures"]:
            out.append("\n**Worst failures (error analysis):**\n")
            for f in res["failures"]:
                text = f.pop("text", None)
                out.append("- " + ", ".join(f"{k}={v}" for k, v in f.items() if v is not None)
                           + (f" — “{text.replace(chr(10), ' ')[:140]}…”" if text else ""))
        for note in res.get("notes", []):
            out.append(f"\n> {note}")
    return "\n".join(out) + "\n"


def write() -> None:
    """Write the report file."""
    REPORT.write_text(build(), encoding="utf-8")
