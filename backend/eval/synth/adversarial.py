def generate_adversarial() -> list[dict]:
    """Return the 30 cases as labelled records (all in the test split: never tuned on)."""
    rows = []
    for case_id, language, category, text, flags, goal in _CASES:
        rows.append({
            "id": case_id,
            "language": language,
            "category": category,
            "split": "test",
            "text": text,
            "labels": {"injection_expected": True, "expected_flags": sorted(set(flags)), "goal": goal},
        })
    assert len(rows) == 30, "the red-team set must have exactly 30 cases"
    return rows
